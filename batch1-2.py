# 3. Menghitung no-show rate berdasarkan slot waktu
# Mengambil jam dari rentang waktu
def categorize_time(range_str):
    start_time, _ = range_str.split('-')
    return start_time

# Membuat salinan kolom untuk menghindari perubahan pada dataset asli
df_temp = df.copy()

# Ekstrak start_time sebagai kolom terpisah
df_temp['start_time'] = df_temp['jam_jadwal'].apply(categorize_time)

# Mengonversi start_time ke format datetime
df_temp['start_time'] = pd.to_datetime(df_temp['start_time'], format='%H:%M', errors='coerce').dt.time

# Menentukan kategori waktu berdasarkan start_time
df_temp['kategori_waktu'] = pd.cut(pd.to_datetime(df_temp['start_time'].astype(str)).dt.hour,
bins=[6, 12, 15, 19],
labels=['Pagi', 'Siang', 'Sore'],
right=False)

# Hitung total pendaftaran dan no-show per kategori waktu
total_per_waktu = df_temp.groupby('kategori_waktu').size()
no_show_per_waktu = df_temp[df_temp['status_kehadiran'] == 'TIDAK HADIR'].groupby('kategori_waktu').size()

# Hitung no-show rate
no_show_rate = (no_show_per_waktu / total_per_waktu) * 100

# Ambil nilai no-show rate untuk pagi, siang, dan sore
no_show_pagi = no_show_rate.get('Pagi', 0)
no_show_siang = no_show_rate.get('Siang', 0)
no_show_sore = no_show_rate.get('Sore', 0)

print(f'No-show rate pada slot Pagi: {no_show_pagi:.2f}%')
print(f'No-show rate pada slot Siang: {no_show_siang:.2f}%')
print(f'No-show rate pada slot Sore: {no_show_sore:.2f}%')

# 4. Menghitung no-show rate berdasarkan jenis pasien (LAMA/BARU)
# Hitung total pasien berdasarkan jenis dan no-show
