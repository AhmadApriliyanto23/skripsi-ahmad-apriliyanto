no_show_lama = no_show_rate_jenis.get('LAMA', 0)

print(f'No-show rate untuk pasien Baru: {no_show_baru:.2f}%')
print(f'No-show rate untuk pasien Lama: {no_show_lama:.2f}%')
print()

